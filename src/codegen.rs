//! # Rocket - Code Generation for TypeScript & NAPI
//!
//! This module implements the code generation layer and metadata bridges for
//! Rocket web framework NAPI bindings in TypeScript / Node.js.
//!
//! Rocket's core codegen features (custom derives, attributes, procedural macros)
//! in Rust (`#[get]`, `routes!`, `uri!`, `#[catch]`, `derive(FromForm)`, `derive(Responder)`)
//! operate at compile time. In TypeScript / Node.js environments, code generation is
//! supported through NAPI runtime bindings, TypeScript metadata generators, and
//! route manifest builders.
//!
//! # TypeScript Codegen & Macro Parity
//!
//! * **Route Attributes (`#[get("/path")]`, etc.)**: Supported via dynamic route definitions
//!   and TypeScript decorators / route map objects.
//! * **Route Table (`routes![...]`)**: Supported via [`generate_routes_manifest`] and
//!   `Alloy.serve({ routes: { ... } })`.
//! * **URI Building (`uri!(...)`)**: Supported via [`build_uri`] / [`RouteMetadata`].
//! * **Catchers (`#[catch(404)]`)**: Supported via [`CatcherMetadata`].
//! * **Config & Launch (`#[launch]`, `#[main]`)**: Supported via `Rocket::new()`, `launch()`, and `serve()`.

use std::collections::HashMap;
use napi_derive::napi;

/// Metadata for a registered Rocket route, mirroring Rocket's route attribute codegen output.
#[napi(object)]
#[derive(Clone, Debug)]
pub struct RouteMetadata {
    pub method: String,
    pub uri: String,
    pub name: Option<String>,
    pub rank: Option<i32>,
    pub format: Option<String>,
}

/// Metadata for a Rocket error catcher, mirroring Rocket's `#[catch]` attribute output.
#[napi(object)]
#[derive(Clone, Debug)]
pub struct CatcherMetadata {
    pub code: Option<u32>,
    pub name: Option<String>,
}

/// Helper function to create a [`RouteMetadata`] instance.
#[napi]
pub fn create_route_metadata(
    method: String,
    uri: String,
    name: Option<String>,
    rank: Option<i32>,
    format: Option<String>,
) -> RouteMetadata {
    RouteMetadata {
        method,
        uri,
        name,
        rank,
        format,
    }
}

/// Code generation helper: Generates a TypeScript routes manifest string from a list of [`RouteMetadata`].
///
/// This provides TS/Node.js codegen tools with structured route type definitions and handler tables,
/// serving as the NAPI equivalent of Rocket's `routes!` macro expansion.
#[napi]
pub fn generate_routes_manifest(
    routes: Vec<RouteMetadata>,
    catchers: Option<Vec<CatcherMetadata>>,
) -> String {
    let mut out = String::from("// Generated by Rocket NAPI Codegen\n");
    out.push_str("export const routesManifest = [\n");
    for r in &routes {
        out.push_str(&format!(
            "  {{ method: {:?}, uri: {:?}, name: {:?}, rank: {:?}, format: {:?} }},\n",
            r.method, r.uri, r.name, r.rank, r.format
        ));
    }
    out.push_str("] as const;\n\n");

    if let Some(catchers) = catchers {
        out.push_str("export const catchersManifest = [\n");
        for c in &catchers {
            out.push_str(&format!(
                "  {{ code: {:?}, name: {:?} }},\n",
                c.code, c.name
            ));
        }
        out.push_str("] as const;\n");
    }

    out
}

/// Type-safe URI builder helper, providing NAPI runtime support for Rocket's `uri!` macro semantics in TypeScript.
#[napi]
pub fn build_uri(pattern: String, params: HashMap<String, String>) -> String {
    let mut result = pattern;
    for (k, v) in params {
        let param_key = format!("<{}>", k);
        let param_key_colon = format!(":{}", k);
        let encoded_val = percent_encoding::utf8_percent_encode(&v, percent_encoding::NON_ALPHANUMERIC).to_string();
        result = result.replace(&param_key, &encoded_val);
        result = result.replace(&param_key_colon, &encoded_val);
    }
    result
}
