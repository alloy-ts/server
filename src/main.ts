export function parseRouteUri(path: string, method: string = "GET") {
  const def = native.parseRoute({ path, method });
  const params = [
    ...def.params.map((p: any) => ({
      name: p.name,
      paramType: p.tsType,
      isPath: true,
      isQuery: false,
      isTrailing: p.trailing,
      isOptional: p.optional,
    })),
    ...def.query.map((q: any) => ({
      name: q.name,
      paramType: q.tsType,
      isPath: false,
      isQuery: true,
      isTrailing: q.trailing,
      isOptional: q.optional,
    })),
  ];
  return {
    method: def.method,
    path: def.path,
    rocketPath: def.rocketPath,
    name: def.name,
    params,
  };
}

export function parseRocketRoutePattern(path: string) {
  return parseRouteUri(path, "GET").params;
}

export function generateTsUriBuilder(
  routes: Array<{ name: string; method?: string; path: string }>,
): string {
  const entries = routes.map((r) => {
    const meta = parseRouteUri(r.path, r.method || "GET");
    const pathParams = meta.params.filter((p) => p.isPath);
    const argList = pathParams.map((p) => `${p.name}: string | number`).join(", ");
    let template = r.path;
    for (const p of pathParams) {
      template = template.replace(`:${p.name}`, `\${${p.name}}`);
      template = template.replace(`<${p.name}>`, `\${${p.name}}`);
    }
    return `  ${r.name}: (${argList}) => \`${template}\``;
  });

  return [
    "// Auto-generated by Rocket NAPI Codegen",
    "export const uri = {",
    entries.join(",\n"),
    "};",
  ].join("\n");
}

export function parseCatcherStatus(status: string | number): number | null {
  if (typeof status === "number") {
    return Number.isNaN(status) ? null : status;
  }
  if (typeof status === "string") {
    const trimmed = status.trim().toLowerCase();
    if (trimmed === "default") {
      return null;
    }
    const num = parseInt(trimmed, 10);
    return Number.isNaN(num) ? null : num;
  }
  return null;
}

function createRouteDecorator(method: string) {
  return function (path: string) {
    return function (target: any, _propertyKey?: string, descriptor?: PropertyDescriptor) {
      const handler = descriptor ? descriptor.value : target;
      registerRoute(method, path, handler);
      return descriptor || target;
    };
  };
}

export const get = createRouteDecorator("GET");
export const post = createRouteDecorator("POST");
export const put = createRouteDecorator("PUT");
export const del = createRouteDecorator("DELETE");
export const patch = createRouteDecorator("PATCH");
export const head = createRouteDecorator("HEAD");
export const options = createRouteDecorator("OPTIONS");

export function route(method: string, path: string) {
  return createRouteDecorator(method)(path);
}

export function catch_(status: string | number) {
  parseCatcherStatus(status);
  return function (target: any, _propertyKey?: string, descriptor?: PropertyDescriptor) {
    return descriptor || target;
  };
}

export function generateTypescriptClient(defs: any[], options?: any) {
  const formattedDefs = defs.map((d) =>
    native.parseRoute({
      method: d.method || "GET",
      path: d.path,
      name: d.name,
      body: d.body || d.bodyType,
      response: d.response || d.returnType,
    }),
  );
  const code = native.generateClient(formattedDefs, options);
  return { code };
}

export function generateRouteHandler(routeDef: any): string {
  const meta = parseRouteUri(routeDef.path, routeDef.method || "GET");
  return `export async function ${meta.name}Handler(req: RequestInput) {\n  // Handler implementation for ${meta.method} ${meta.path}\n  return new Response("OK");\n}`;
}

export function generateTypescriptInterface(name: string, fields: Record<string, string>): string {
  const body = Object.entries(fields)
    .map(([k, v]) => `  ${k}: ${v};`)
    .join("\n");
  return `export interface ${name} {\n${body}\n}`;
}

