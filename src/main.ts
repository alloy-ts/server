export function translatePattern(pattern: string): string {
  return native.toRocketPath(pattern);
}

export function parseRouteUri(pattern: string, method = "GET") {
  const route = native.parseRoute({ method, path: pattern });
  const rawQuery = pattern.includes("?") ? pattern.slice(pattern.indexOf("?")) : "";
  const rocketPath = route.rocketPath + rawQuery;
  return {
    method: route.method,
    path: route.path,
    rocketPath,
    params: [
      ...route.params.map((p) => ({
        name: p.name,
        isQuery: false,
        isTrailing: p.trailing,
        isOptional: p.optional,
      })),
      ...route.query.map((q) => ({
        name: q.name,
        isQuery: true,
        isTrailing: pattern.includes(`<${q.name}..>`) || pattern.includes(`${q.name}..`),
        isOptional: true,
      })),
    ],
  };
}

export function generateTsUriBuilder(
  routes: Array<{ name: string; method: string; path: string }>,
): string {
  const defs = native.parseRoutes(
    routes.map((r) => ({ method: r.method, path: r.path, name: r.name })),
  );
  const uriEntries = defs
    .map((d) => {
      let pathExpr = d.path;
      for (const p of d.params) {
        if (p.trailing) {
          pathExpr = pathExpr.replace("*", "");
        } else {
          pathExpr = pathExpr.replace(`:${p.name}`, `\${${p.tsName}}`);
        }
      }
      const paramArgs = d.params.map((p) => `${p.tsName}: string | number`).join(", ");
      return `  ${d.name}: (${paramArgs}) => \`${pathExpr}\`,`;
    })
    .join("\n");

  return `// Auto-generated by Rocket NAPI Codegen\nexport const uri = {\n${uriEntries}\n};`;
}

export function parseCatcherStatus(status: string): number | null {
  if (status.toLowerCase() === "default") {
    return null;
  }
  const code = parseInt(status, 10);
  return isNaN(code) ? null : code;
}

export function get(path: string) {
  return function (target: any, key: string) {
    native.registerRoute("GET", path, target[key]);
  };
}

