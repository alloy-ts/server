//! NAPI bindings for Rocket's [`Route`] (`rocket::Route`) and [`StaticInfo`].

use napi_derive::napi;

use rocket::http::Method;
use rocket::route::dummy_handler;
use rocket::route::Route as RocketRoute;

/// NAPI wrapper for `rocket::Route`.
#[napi]
pub struct Route {
    pub name: Option<String>,
    pub method: String,
    pub uri: String,
    pub rank: i64,
    pub format: Option<String>,
}

#[napi]
impl Route {
    /// Creates a new route with the given method and path, with a base of `/` and computed default rank.
    #[napi(constructor)]
    pub fn new(method: String, uri: String) -> napi::Result<Self> {
        let m: Method = method
            .parse()
            .map_err(|_| napi::Error::new(napi::Status::GenericFailure, format!("invalid method: {method}")))?;

        let rocket_route = RocketRoute::new(m, &uri, dummy_handler);
        Ok(Route {
            name: rocket_route.name.map(|n| n.to_string()),
            method: rocket_route.method.as_str().to_string(),
            uri: rocket_route.uri.to_string(),
            rank: rocket_route.rank as i64,
            format: rocket_route.format.map(|f| f.to_string()),
        })
    }

    /// Creates a new route with explicit rank, method, and URI.
    #[napi]
    pub fn ranked(rank: Option<i64>, method: String, uri: String) -> napi::Result<Self> {
        let m: Method = method
            .parse()
            .map_err(|_| napi::Error::new(napi::Status::GenericFailure, format!("invalid method: {method}")))?;

        let rank_isize = rank.map(|r| r as isize);
        let rocket_route = RocketRoute::ranked(rank_isize, m, &uri, dummy_handler);
        Ok(Route {
            name: rocket_route.name.map(|n| n.to_string()),
            method: rocket_route.method.as_str().to_string(),
            uri: rocket_route.uri.to_string(),
            rank: rocket_route.rank as i64,
            format: rocket_route.format.map(|f| f.to_string()),
        })
    }

    /// Maps the base of this route using a prefix or base string.
    #[napi]
    pub fn map_base(&self, base: String) -> napi::Result<Self> {
        let current_uri = &self.uri;
        let new_uri = if base == "/" {
            current_uri.clone()
        } else {
            format!("{}{}", base.trim_end_matches('/'), current_uri)
        };
        Ok(Route {
            name: self.name.clone(),
            method: self.method.clone(),
            uri: new_uri,
            rank: self.rank,
            format: self.format.clone(),
        })
    }
}

/// Information generated by Rocket's `route` attribute during codegen.
#[napi(object)]
pub struct StaticInfo {
    pub name: String,
    pub method: String,
    pub uri: String,
    pub format: Option<String>,
    pub rank: Option<i64>,
}
