import { expect, test } from "vite-plus/test";
import {
  translatePattern,
  parseRouteUri,
  generateTsUriBuilder,
  parseCatcherStatus,
  get,
  Alloy,
} from "./main.ts";

test("translatePattern converts Express/Bun patterns to Rocket syntax", () => {
  expect(translatePattern("/users/:id")).toBe("/users/<id>");
  expect(translatePattern("/api/:version/users/:id/*")).toBe("/api/<version>/users/<id>/<_..>");
  expect(translatePattern("/static/*")).toBe("/static/<_..>");
  expect(translatePattern("/plain")).toBe("/plain");
});

test("parseRouteUri extracts path and query dynamic parameters", () => {
  const meta = parseRouteUri("/posts/:slug?<query>&<rest..>", "GET");
  expect(meta.method).toBe("GET");
  expect(meta.rocketPath).toBe("/posts/<slug>?<query>&<rest..>");

  const pathParams = meta.params.filter((p: any) => !p.isQuery);
  expect(pathParams.length).toBe(1);
  expect(pathParams[0].name).toBe("slug");

  const queryParams = meta.params.filter((p: any) => p.isQuery);
  expect(queryParams.length).toBe(2);
  expect(queryParams[0].name).toBe("query");
  expect(queryParams[1].name).toBe("rest");
  expect(queryParams[1].isTrailing).toBe(true);
});

test("generateTsUriBuilder produces valid TypeScript uri helper code", () => {
  const code = generateTsUriBuilder([
    { name: "getUser", method: "GET", path: "/users/:id" },
    { name: "getPost", method: "GET", path: "/posts/:category/:slug" },
  ]);

  expect(code).toContain("// Auto-generated by Rocket NAPI Codegen");
  expect(code).toContain("export const uri = {");
  expect(code).toContain("getUser: (id: string | number) => `/users/${id}`");
  expect(code).toContain(
    "getPost: (category: string | number, slug: string | number) => `/posts/${category}/${slug}`",
  );
});

test("parseCatcherStatus parses numeric codes and default keyword", () => {
  expect(parseCatcherStatus("404")).toBe(404);
  expect(parseCatcherStatus("500")).toBe(500);
  expect(parseCatcherStatus("default")).toBe(null);
  expect(parseCatcherStatus("DEFAULT")).toBe(null);
});

test("TypeScript route registration and Alloy helpers work correctly", () => {
  const routeDecorator = get("/api/items/:id");
  expect(typeof routeDecorator).toBe("function");

  const uriCode = Alloy.generateUriBuilder([
    { name: "item", method: "GET", path: "/api/items/:id" },
  ]);
  expect(uriCode).toContain("item: (id: string | number) => `/api/items/${id}`");
});

test("generateTypescriptClient and interface codegen utilities work correctly", () => {
  const clientRes = Alloy.generateTypescriptClient([
    { name: "getUser", method: "GET", path: "/users/:id", returnType: "User" },
  ]);
  expect(clientRes.code).toContain("export class RocketClient");

  const routeHandlerCode = Alloy.generateTypescriptClient([
    { name: "getPost", method: "GET", path: "/posts/:id", returnType: "Post" },
  ]);
  expect(routeHandlerCode.code).toContain("getPost");
});
