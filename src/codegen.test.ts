import { expect, test, describe } from "vite-plus/test";
import {
  httpMethods,
  parseRoute,
  parseRoutes,
  toRocketPath,
  generateTypes,
  generateClient,
  generateModule,
  type ParamKind,
  type RouteInput,
  type CodegenOptions,
} from "../dist/index.js";

describe("Rocket codegen NAPI bindings", () => {
  test("httpMethods returns all supported HTTP methods", () => {
    const methods = httpMethods();
    expect(methods).toContain("GET");
    expect(methods).toContain("POST");
    expect(methods).toContain("PUT");
    expect(methods).toContain("DELETE");
    expect(methods).toContain("PATCH");
    expect(methods).toContain("OPTIONS");
    expect(methods).toContain("HEAD");
    expect(methods).toContain("TRACE");
    expect(methods).toContain("CONNECT");
    expect(methods.length).toBe(9);
  });

  describe("parseRoute", () => {
    test("parses Bun/Alloy style route pattern", () => {
      const input: RouteInput = {
        method: "get",
        path: "/users/:id/posts/*",
      };
      const route = parseRoute(input);

      expect(route.method).toBe("GET");
      expect(route.path).toBe("/users/:id/posts/*");
      expect(route.rocketPath).toBe("/users/<id>/posts/<_..>");
      expect(route.key).toBe("GET /users/:id/posts/*");
      expect(route.name).toBe("getUsersByIdPosts");
      expect(route.params.length).toBe(2);

      expect(route.params[0]).toEqual({
        name: "id",
        tsName: "id",
        kind: "Path" as ParamKind,
        tsType: "string | number",
        trailing: false,
        optional: false,
      });

      expect(route.params[1]).toEqual({
        name: "_",
        tsName: "_",
        kind: "Path" as ParamKind,
        tsType: "string[]",
        trailing: true,
        optional: true,
      });
    });

    test("parses Rocket style route pattern with query parameters", () => {
      const input: RouteInput = {
        method: "POST",
        path: "/users/<id..>?<q>&closed",
        body: "CreateUser",
        response: "User",
      };
      const route = parseRoute(input);

      expect(route.method).toBe("POST");
      expect(route.path).toBe("/users/:id");
      expect(route.rocketPath).toBe("/users/<id..>");
      expect(route.key).toBe("POST /users/:id");
      expect(route.body).toBe("CreateUser");
      expect(route.response).toBe("User");

      expect(route.params[0]?.trailing).toBe(true);

      expect(route.query.length).toBe(2);
      expect(route.query[0]?.name).toBe("q");
      expect(route.query[1]?.name).toBe("closed");
      expect(route.query.every((q) => q.optional)).toBe(true);
    });

    test("handles root route and throws on unknown HTTP methods", () => {
      const route = parseRoute({ method: "GET", path: "/" });
      expect(route.name).toBe("get");
      expect(route.path).toBe("/");

      expect(() => parseRoute({ method: "FETCH", path: "/" })).toThrow(/invalid HTTP method/);
    });

    test("sanitizes reserved TypeScript words and invalid parameter names", () => {
      const input: RouteInput = {
        method: "GET",
        path: "/items/:type?2fa",
        paramTypes: [
          {
            name: "type",
            tsType: '"a" | "b"',
          },
        ],
      };
      const route = parseRoute(input);

      expect(route.params[0]?.tsName).toBe("type_");
      expect(route.params[0]?.tsType).toBe('"a" | "b"');

      expect(route.query[0]?.tsName).toBe("param0_2fa");
    });
  });

  describe("parseRoutes", () => {
    test("deduplicates route handler names", () => {
      const inputs: RouteInput[] = [
        { method: "GET", path: "/a/:id" },
        { method: "GET", path: "/a/:id" },
        { method: "POST", path: "/a/:id" },
      ];
      const routes = parseRoutes(inputs);

      expect(routes.length).toBe(3);
      expect(routes[0]?.name).toBe("getAById");
      expect(routes[1]?.name).toBe("getAById_2");
      expect(routes[2]?.name).toBe("postAById");
    });
  });

  describe("toRocketPath", () => {
    test("translates path patterns to Rocket format", () => {
      expect(toRocketPath("/a/:b/*")).toBe("/a/<b>/<_..>");
      expect(toRocketPath("/a/<b..>")).toBe("/a/<b..>");
      expect(toRocketPath("/a/<_>")).toBe("/a/<_..>");
      expect(toRocketPath("/users/:id")).toBe("/users/<id>");
    });
  });

  describe("code generation functions", () => {
    const routeInput: RouteInput = {
      method: "GET",
      path: "/users/:id?<active>",
      response: "User",
    };

    test("generateTypes produces TypeScript type declarations", () => {
      const route = parseRoute(routeInput);
      const types = generateTypes([route]);

      expect(types).toContain("// Code generated by alloy-server-native");
      expect(types).toContain("export interface RouteTypes {");
      expect(types).toContain('"GET /users/:id": {');
      expect(types).toContain("id: string | number;");
      expect(types).toContain("active?: string | number;");
      expect(types).toContain("response: User;");
      expect(types).toContain("export type ParamsOf<K extends RouteKey>");
      expect(types).toContain("export interface RouteContext<K extends RouteKey>");
      expect(types).not.toContain("export class");
      expect(types).not.toContain("export function uri(");
    });

    test("generateTypes honors custom options", () => {
      const route = parseRoute(routeInput);
      const options: CodegenOptions = {
        banner: false,
        typesName: "ApiRoutes",
        serverImport: "@alloy-ts/server",
      };
      const types = generateTypes([route], options);

      expect(types).not.toContain("// Code generated by alloy-server-native");
      expect(types).toContain("export interface ApiRoutes {");
      expect(types).toContain(
        'import type { RequestInput as RequestLike } from "@alloy-ts/server";',
      );
    });

    test("generateClient produces a typed fetch client SDK", () => {
      const route = parseRoute(routeInput);
      const clientCode = generateClient([route]);

      expect(clientCode).toContain("export class RocketClient {");
      expect(clientCode).toContain("export function uri(");
      expect(clientCode).toContain("async getUsersById(");
      expect(clientCode).toContain('as ResponseOf<"GET /users/:id">;');
    });

    test("generateClient with external types import", () => {
      const route = parseRoute(routeInput);
      const options: CodegenOptions = {
        clientName: "UserApiClient",
        baseUrl: "https://api.example.com",
        typesImport: "./types.ts",
      };
      const clientCode = generateClient([route], options);

      expect(clientCode).toContain(
        'import type { ParamsOf, QueryOf, BodyOf, ResponseOf } from "./types.ts";',
      );
      expect(clientCode).toContain("export class UserApiClient {");
      expect(clientCode).toContain("https://api.example.com");
    });

    test("generateModule produces full standalone code module", () => {
      const route = parseRoute(routeInput);
      const moduleCode = generateModule([route]);

      expect(moduleCode).toContain("export const ROUTES = {");
      expect(moduleCode).toContain('"GET /users/:id": "/users/:id",');
      expect(moduleCode).toContain("export interface RouteTypes {");
      expect(moduleCode).toContain("export function uri(");
      expect(moduleCode).toContain("export class RocketClient {");
    });
  });
});
