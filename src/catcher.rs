//! NAPI bindings for Rocket's [`Catcher`] (`rocket::Catcher`).

use napi_derive::napi;
use rocket::http::uri::Origin;

/// NAPI wrapper for Rocket's error catching route (`rocket::Catcher`).
#[napi]
pub struct Catcher {
    pub name: Option<String>,
    pub base: String,
    pub code: Option<u32>,
}

#[napi]
impl Catcher {
    /// Creates a catcher for the given status code (400-599), or a default catcher if status is null.
    #[napi(constructor)]
    pub fn new(code: Option<u32>) -> napi::Result<Self> {
        if let Some(c) = code {
            if !(400..600).contains(&c) {
                return Err(napi::Error::new(
                    napi::Status::InvalidArg,
                    format!("Status code {c} is out of valid error range [400, 600)"),
                ));
            }
        }

        Ok(Catcher {
            name: None,
            base: "/".to_string(),
            code,
        })
    }

    /// Creates a default error catcher with no specific status code.
    #[napi]
    pub fn default_catcher() -> Self {
        Catcher {
            name: Some("<Rocket Catcher>".to_string()),
            base: "/".to_string(),
            code: None,
        }
    }

    /// Maps the base path of this catcher using the provided base URI string.
    #[napi]
    pub fn map_base(&mut self, base: String) -> napi::Result<String> {
        let origin = Origin::parse_owned(base)
            .map_err(|e| napi::Error::new(napi::Status::InvalidArg, e.to_string()))?
            .into_normalized();
        self.base = origin.path().to_string();
        Ok(self.base.clone())
    }
}

/// Information generated by the `catch` attribute during codegen.
#[napi(object)]
pub struct CatcherInfo {
    pub name: String,
    pub code: Option<u32>,
}
